class ModelOptNvFp4Config(ModelOptQuantConfigBase):
    """Config class for ModelOpt FP4."""

    def __init__(
        self,
        quant_method: str = "NVFP4",
        is_checkpoint_nvfp4_serialized: bool = False,
        kv_cache_quant_algo: str | None = None,
        exclude_modules: list[str] | None = None,
        group_size: int = 16,
    ) -> None:
        if exclude_modules is None:
            exclude_modules = []
        super().__init__(exclude_modules)
        self.quant_method = quant_method
        self.is_checkpoint_nvfp4_serialized = is_checkpoint_nvfp4_serialized
        if is_checkpoint_nvfp4_serialized:
            logger.warning(
                "Detected ModelOpt NVFP4 checkpoint (quant_algo=%s). Please "
                "note that the format is experimental and could change in "
                "future.",
                quant_method,
            )

            self.group_size = group_size
            self.kv_cache_quant_algo = kv_cache_quant_algo

        # Select LinearMethod implementation based on quant_algo (FP8 pattern).
        # NVFP4         -> W4A4: cutlass NVFP4 GEMM with input quantization
        # W4A16_NVFP4   -> W4A16: FP4 Marlin GEMM with bf16/fp16 activations
        if quant_method == "NVFP4":
            self.LinearMethodCls = ModelOptNvFp4LinearMethod
        elif quant_method == "W4A16_NVFP4":
            self.LinearMethodCls = ModelOptNvFp4W4A16LinearMethod
        else:
            raise ValueError(
                f"Unsupported ModelOpt NVFP4 quant_algo: {quant_method}. "
                "Supported: NVFP4 / W4A16_NVFP4."
            )

    def get_name(self) -> QuantizationMethods:
        return "modelopt_fp4"

    def get_supported_act_dtypes(self) -> list[torch.dtype]:
        return [torch.bfloat16, torch.half, torch.float8_e4m3fn]

    @classmethod
    def get_min_capability(cls) -> int:
        return 75

    @classmethod
    def override_quantization_method(
        cls, hf_quant_cfg, user_quant, hf_config=None
    ) -> QuantizationMethods | None:
        algo = cls._extract_modelopt_quant_algo(hf_quant_cfg)
        if algo is not None and ("NVFP4" in algo or "FP4" in algo):
            return "modelopt_fp4"
        return None

    @classmethod
    def _from_config(
        cls,
        *,
        quant_method: str,
        kv_cache_quant_method: str | None,
        exclude_modules: list[str],
        original_config: dict[str, Any],
        group_size: int | None,
        **kwargs: Any,
    ) -> "ModelOptNvFp4Config":
        is_checkpoint_nvfp4_serialized = "NVFP4" in quant_method

        if group_size is None:
            group_size = 16  # Default value

        # For FP4, these fields are required
        if is_checkpoint_nvfp4_serialized and "quantization" in original_config:
            # Check if required fields are present in the quantization config
            quant_config = original_config["quantization"]
            required_fields = ["group_size", "kv_cache_quant_algo", "exclude_modules"]
            missing_fields = [
                field for field in required_fields if field not in quant_config
            ]
            if missing_fields:
                raise ValueError(
                    f"NVFP4 quantization requires the following fields in "
                    f"hf_quant_config.json: {missing_fields}"
                )

        return cls(
            quant_method,
            is_checkpoint_nvfp4_serialized,
            kv_cache_quant_method,
            exclude_modules,
            group_size,
        )


class ModelOptNvFp4LinearMethod(LinearMethodBase):
    """Linear method for Model Optimizer NVFP4.
    Supports loading NVFP4 checkpoints with the following structure:

    input_scale: torch.float32, scalar ,
    weight: NVFP4(represented as byte) Shape: [1, X, y/2]
    weight_scale: FP8-E4M3, Shape: [X, Y], aka per block scale,
    weight_scale_2: torch.float32, scalar,
    Args: quant_config: The ModelOpt quantization config.
    """

    def __init__(self, quant_config: ModelOptNvFp4Config) -> None:
        self.quant_config = quant_config
        self.marlin_input_dtype = None
        self.kernel = init_nvfp4_linear_kernel()

    def create_weights(
        self,
        layer: torch.nn.Module,
        input_size_per_partition: int,
        output_partition_sizes: list[int],
        input_size: int,
        output_size: int,
        params_dtype: torch.dtype,
        **extra_weight_attrs,
    ):
        del input_size, output_size
        if not self.quant_config.is_checkpoint_nvfp4_serialized:
            raise ValueError(
                "NVFP4 quantization was selected, "
                " dynamic quantization is not supported."
            )
        output_size_per_partition = sum(output_partition_sizes)
        weight_loader = extra_weight_attrs.get("weight_loader")
        layer.logical_widths = output_partition_sizes
        layer.input_size_per_partition = input_size_per_partition
        layer.output_size_per_partition = output_size_per_partition

        if input_size_per_partition % 16 != 0:
            raise ValueError(
                "Unsupported model when in features size is not multiple of 16"
            )
        # The nvfp4 weight is still represented as
        weight_dtype = (
            torch.float8_e4m3fn
            if self.quant_config.is_checkpoint_nvfp4_serialized
            else params_dtype
        )
        # Weight
        weight = ModelWeightParameter(
            data=torch.empty(
                # 2 fp4 items are packed in the input dimension
                layer.output_size_per_partition,
                layer.input_size_per_partition // 2,
                dtype=torch.uint8,
            ),
            input_dim=1,
            output_dim=0,
            weight_loader=weight_loader,
        )
        layer.register_parameter("weight", weight)

        # Input Global Scale
        input_global_scale = PerTensorScaleParameter(
            data=torch.empty(len(output_partition_sizes), dtype=torch.float32),
            weight_loader=weight_loader,
        )
        layer.register_parameter("input_scale", input_global_scale)

        # Weight Global Scale
        weight_global_scale = PerTensorScaleParameter(
            data=torch.empty(len(output_partition_sizes), dtype=torch.float32),
            weight_loader=weight_loader,
        )
        layer.register_parameter("weight_scale_2", weight_global_scale)

        # Per Block Weight Scale
        weight_scale = ModelWeightParameter(
            data=torch.empty(
                output_size_per_partition,
                input_size_per_partition // self.quant_config.group_size,
                dtype=weight_dtype,
            ),
            input_dim=1,
            output_dim=0,
            weight_loader=weight_loader,
        )

        layer.register_parameter("weight_scale", weight_scale)

        expose_input_quant_key(layer, self.kernel)

    def process_weights_after_loading(self, layer: torch.nn.Module) -> None:
        if (
            torch.unique(layer.input_scale).numel() != 1
            or torch.unique(layer.weight_scale_2).numel() != 1
        ):
            logger.warning_once(
                "In NVFP4 linear, the global scale for input or weight are different"
                " for parallel layers (e.g. q_proj, k_proj, v_proj). This "
                " will likely results in reduce accuracy. Please verify the model"
                " accuracy. Consider using a checkpoint with a shared global NVFP4"
                " scale for parallel layers."
            )

        # Rename ModelOpt checkpoint names to standardized names
        input_global_scale = layer.input_scale.max().to(torch.float32)
        layer.input_global_scale = Parameter(input_global_scale, requires_grad=False)
        del layer.input_scale

        weight_global_scale = layer.weight_scale_2.max().to(torch.float32)
        layer.weight_global_scale = Parameter(weight_global_scale, requires_grad=False)
        del layer.weight_scale_2

        # Pre-compute alpha and inverse for runtime quantization
        layer.alpha = Parameter(
            layer.input_global_scale * layer.weight_global_scale, requires_grad=False
        )
        layer.input_global_scale_inv = Parameter(
            (1.0 / layer.input_global_scale).to(torch.float32), requires_grad=False
        )

        # Convert layer to NVFP4 linear kernel format
        self.kernel.process_weights_after_loading(layer)

    def apply(
        self,
        layer: torch.nn.Module,
        x: torch.Tensor,
        bias: torch.Tensor | None = None,
    ) -> torch.Tensor:
        return self.kernel.apply_weights(layer=layer, x=x, bias=bias)


class ModelOptNvFp4W4A16LinearMethod(LinearMethodBase):
    """Linear method for ModelOpt NVFP4 W4A16.

    4-bit NVFP4 weights, fp16/bf16 activations. Loads ModelOpt-style names
    directly (no on-disk conversion) and dispatches to a W4A16 GEMM:

        weight          uint8     packed NVFP4 (2 nibbles/byte along input dim)
        weight_scale    fp8-e4m3  per 16-elem group along input dim
        weight_scale_2  fp32      per-tensor global scale = amax / (6.0 * 448.0)

    No activation quantization. ModelOpt stores the global scale as
    amax/2688, so we rename weight_scale_2 -> weight_global_scale without
    reciprocation. The selected kernel converts it to its runtime format.
    The CT W4A16 path reciprocates because CT stores the inverse on disk.

    We also register a placeholder input_scale parameter so that W4A4-shaped
    checkpoints (which contain *_proj.input_scale tensors) can be loaded
    under this method without the per-shard loader hitting a KeyError on
    the merged-name lookup. The placeholder is discarded in
    process_weights_after_loading -- its value is never used.
    """

    def __init__(self, quant_config: ModelOptNvFp4Config) -> None:
        self.quant_config = quant_config
        self.marlin_input_dtype = None
        # `init_nvfp4_linear_kernel(use_a16=True)` is best of both worlds:
        # 1. `use_a16=True` forces  `Marlin`: https://github.com/vllm-project/vllm/commit/e68988a#diff-7135ab92aa94dfacb1ad3c77fc13f9c4ffe0b977f8eac5d86c2afe243e5f92a6R842-R889
        # for `--linear-backend=auto`, avoiding a W4A4 kernel that requires input_scale.
        # 2. Specifying e.g. `--linear-backend=humming` will override.
        self.kernel = init_nvfp4_linear_kernel(use_a16=True)

    def create_weights(
        self,
        layer: torch.nn.Module,
        input_size_per_partition: int,
        output_partition_sizes: list[int],
        input_size: int,
        output_size: int,
        params_dtype: torch.dtype,
        **extra_weight_attrs,
    ):
        del input_size, output_size
        if not self.quant_config.is_checkpoint_nvfp4_serialized:
            raise ValueError(
                "W4A16_NVFP4 quantization was selected; "
                "dynamic quantization is not supported."
            )
        output_size_per_partition = sum(output_partition_sizes)
        weight_loader = extra_weight_attrs.get("weight_loader")
        layer.logical_widths = output_partition_sizes
        layer.input_size_per_partition = input_size_per_partition
        layer.output_size_per_partition = output_size_per_partition
        layer.output_partition_sizes = output_partition_sizes

        if input_size_per_partition % 16 != 0:
            raise ValueError(
                "Unsupported model: input feature size is not a multiple of 16."
            )

        # Packed NVFP4 weights: uint8, 2 nibbles per byte along the input dim.
        weight = ModelWeightParameter(
            data=torch.empty(
                output_size_per_partition,
                input_size_per_partition // 2,
                dtype=torch.uint8,
            ),
            input_dim=1,
            output_dim=0,
            weight_loader=weight_loader,
        )
        layer.register_parameter("weight", weight)

        # Per-tensor global weight scale (fp32). ModelOpt stores
        # amax / (NVFP4_max * fp8_e4m3_max) = amax / 2688. PerTensorScaleParameter
        # holds one entry per fused output partition (e.g. q/k/v in a fused QKV).
        weight_scale_2 = PerTensorScaleParameter(
            data=torch.empty(len(output_partition_sizes), dtype=torch.float32),
            weight_loader=weight_loader,
        )
        layer.register_parameter("weight_scale_2", weight_scale_2)

        # Per-group fp8 weight scale.
        weight_scale = GroupQuantScaleParameter(
            data=torch.empty(
                output_size_per_partition,
                input_size_per_partition // self.quant_config.group_size,
                dtype=torch.float8_e4m3fn,
            ),
            input_dim=1,
            output_dim=0,
            weight_loader=weight_loader,
        )
        layer.register_parameter("weight_scale", weight_scale)

        # Placeholder input_scale param so W4A4-shaped checkpoints can be
        # loaded under this method without KeyError on the merged-name
        # lookup (qwen2-style stacked-loader path renames *_proj.input_scale
        # to e.g. qkv_proj.input_scale and looks it up unconditionally).
        # Discarded in process_weights_after_loading; never read by the kernel.
        # For native W4A16 checkpoints (no input_scale on disk) the param
        # stays uninitialized and is simply deleted.
        input_scale = PerTensorScaleParameter(
            data=torch.empty(len(output_partition_sizes), dtype=torch.float32),
            weight_loader=weight_loader,
        )
        layer.register_parameter("input_scale", input_scale)

    def process_weights_after_loading(self, layer: torch.nn.Module) -> None:
        if not hasattr(layer, "has_bias"):
            layer.has_bias = getattr(layer, "bias", None) is not None

        # Discard the input_scale placeholder. Whether it carries values
        # (W4A4 ckpt loaded as W4A16) or is uninitialized (native W4A16
        # ckpt), W4A16 mode does not quantize activations, so this is unused.
        if hasattr(layer, "input_scale"):
            del layer.input_scale

        if torch.unique(layer.weight_scale_2).numel() != 1:
            logger.warning_once(
                "In W4A16_NVFP4 linear, the global weight scale "
                "(weight_scale_2) differs across fused parallel layers "
                "(e.g. q/k/v_proj). This will likely reduce accuracy. "
                "Consider a checkpoint with a shared global scale."
            )

        # Rename weight_scale_2 -> weight_global_scale. NO reciprocation:
        # ModelOpt already stores amax/2688, which is exactly what Marlin
        # consumes via nvfp4_marlin_process_global_scale (called inside the
        # Marlin adapter's process_weights_after_loading).
        layer.weight_global_scale = Parameter(
            layer.weight_scale_2.max().to(torch.float32), requires_grad=False
        )
        del layer.weight_scale_2

        # Drafter-only reduced-vocabulary exact-NVFP4 head + dynamic <=512-row prompt tail.
        # Target `layer` is completely untouched; `draft_head` is attached via object.__setattr__
        # so target named_modules() never sees it, and automatically inherits decode6 TMA4-ILV.
        from vllm.model_executor.draft_vocab import get_draft_vocab_token_ids

        draft_ids = get_draft_vocab_token_ids()
        if (
            draft_ids is not None
            and layer.output_size_per_partition >= 65536
            and max(draft_ids) < layer.output_size_per_partition
        ):
            import os
            from statistics import median

            dev = layer.weight.device
            vocab_n = int(layer.output_size_per_partition)
            k_dim = int(layer.input_size_per_partition)
            ids = torch.tensor(draft_ids, dtype=torch.long, device=dev)

            # Capture raw NVFP4 tensors BEFORE Marlin repacking if dynamic prompt tail is enabled.
            want_tail = os.environ.get("MUSE_DRAFT_PROMPT_TAIL", "1") != "0"
            raw_w_full = layer.weight.detach().contiguous().clone() if want_tail else None
            raw_s_full = (
                layer.weight_scale.detach().contiguous().clone().view(torch.uint8)
                if want_tail
                else None
            )
            raw_gs_full = (
                layer.weight_global_scale.detach().float().reshape(1).clone()
                if want_tail
                else None
            )

            draft_head = torch.nn.Module()
            draft_head.params_dtype = layer.params_dtype
            draft_head.input_size_per_partition = k_dim
            draft_head.output_size_per_partition = len(draft_ids)
            draft_head.output_partition_sizes = [len(draft_ids)]
            draft_head.logical_widths = [len(draft_ids)]
            draft_head.has_bias = False
            draft_head.register_parameter("bias", None)
            draft_head.register_buffer("token_ids", ids, persistent=False)
            draft_head.tp_size = 1
            draft_head.org_vocab_size = len(draft_ids)
            draft_head.prompt_tail_admitted = False

            fast_dhead_admitted = False
            want_fast_dhead = (
                want_tail
                and raw_w_full is not None
                and raw_s_full is not None
                and raw_gs_full is not None
                and (len(draft_ids) % 64 == 0)
                and (k_dim % 128 == 0)
                and os.environ.get("MUSE_DHEAD_FAST", "1") != "0"
            )
            dhead_impl = os.environ.get("MUSE_DHEAD_IMPL", "4d64").strip().lower()
            if want_fast_dhead and dhead_impl != "hadamard":
                try:
                    import muse_bfx_ext as _bfx

                    if (
                        hasattr(_bfx, "dhead_fast_pack")
                        and hasattr(_bfx, "dhead_fast_argmax")
                        and hasattr(_bfx, "draft_vocab_score_rows")
                    ):
                        dh_bits = int(os.environ.get("MUSE_DHEAD_BITS", "100"))
                        if dh_bits not in (100, 150, 158, 2):
                            raise ValueError(f"unsupported MUSE_DHEAD_BITS={dh_bits}")
                        default_topk = 384 if dh_bits == 100 else (192 if dh_bits in (150, 158) else 128)
                        dh_topk = max(
                            16,
                            min(512, int(os.environ.get("MUSE_DHEAD_TOPK", str(default_topk)))),
                        )

                        dh_blob, dh_rscales, dh_cscales, dh_toks = _bfx.dhead_fast_pack(
                            raw_w_full, raw_s_full, raw_gs_full, ids, dh_bits
                        )
                        in_static = torch.zeros((vocab_n,), dtype=torch.uint8, device=dev)
                        in_static.scatter_(0, ids, 1)
                        tail_ids = torch.full((512,), -1, dtype=torch.int32, device=dev)
                        tail_count = torch.zeros((1,), dtype=torch.int32, device=dev)
                        tail_seen = torch.zeros((vocab_n,), dtype=torch.int32, device=dev)
                        torch.cuda.synchronize(dev)

                        gen = torch.Generator(device=dev).manual_seed(20261130)
                        x_chk = (
                            torch.randn((6, k_dim), generator=gen, device=dev) * 0.5
                        ).to(torch.bfloat16).contiguous()

                        best_lat_ms = 0.0
                        if os.environ.get("MUSE_DRAFT_VOCAB_PLACE", "1") != "0":
                            try:
                                spares = [torch.empty_like(dh_blob) for _ in range(6)]
                                for sp in spares:
                                    sp.copy_(dh_blob)
                                evict = torch.ones((48 << 20) // 4, dtype=torch.float32, device=dev)
                                cands = [dh_blob, *spares]
                                _ = evict.sum()
                                _ = _bfx.dhead_fast_argmax(
                                    x_chk, dh_blob, dh_rscales, dh_cscales, dh_toks,
                                    tail_ids, tail_count, raw_w_full, raw_s_full, raw_gs_full,
                                    1.0, dh_bits, dh_topk,
                                )
                                torch.cuda.synchronize(dev)
                                samples_dh: list[list[float]] = [[] for _ in cands]
                                for _ in range(5):
                                    for ci, buf in enumerate(cands):
                                        _ = evict.sum()
                                        se = torch.cuda.Event(enable_timing=True)
                                        ee = torch.cuda.Event(enable_timing=True)
                                        se.record()
                                        _ = _bfx.dhead_fast_argmax(
                                            x_chk, buf, dh_rscales, dh_cscales, dh_toks,
                                            tail_ids, tail_count, raw_w_full, raw_s_full, raw_gs_full,
                                            1.0, dh_bits, dh_topk,
                                        )
                                        ee.record()
                                        torch.cuda.synchronize(dev)
                                        samples_dh[ci].append(se.elapsed_time(ee))
                                times_dh = [median(s) for s in samples_dh]
                                best_i = min(range(len(cands)), key=times_dh.__getitem__)
                                best_lat_ms = times_dh[best_i]
                                if best_i > 0 and times_dh[0] - times_dh[best_i] >= 0.005:
                                    dh_blob = cands[best_i]
                                    logger.info(
                                        "Fast 4D-64 draft head DRAM placement: saved %.3f ms (%.3f -> %.3f ms)",
                                        times_dh[0] - times_dh[best_i],
                                        times_dh[0],
                                        times_dh[best_i],
                                    )
                                del spares, cands, evict
                                torch.cuda.empty_cache()
                            except Exception as exc_pl:  # noqa: BLE001
                                logger.warning("Fast 4D-64 draft head DRAM placement skipped (%s)", exc_pl)

                        # Load-time self-check without materializing the unused 330 MB NVFP4 draft_head:
                        # build 6 realistic peaked probes directly from raw NVFP4 rows and verify 6/6
                        # exact top-1 recovery + <=1e-4 exact NVFP4 rescore parity + warmup scratch.
                        probe_n = 6
                        probe_pos = torch.tensor(
                            [0, 17, 1024, 16384, 49152, len(draft_ids) - 1],
                            dtype=torch.long,
                            device=dev,
                        )
                        probe_orig = ids.index_select(0, probe_pos)
                        pw = raw_w_full.index_select(0, probe_orig)
                        ps = raw_s_full.index_select(0, probe_orig).view(torch.float8_e4m3fn).float()
                        e2m1_lut = torch.tensor(
                            [0.0, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0,
                             -0.0, -0.5, -1.0, -1.5, -2.0, -3.0, -4.0, -6.0],
                            dtype=torch.float32,
                            device=dev,
                        )
                        lo_v = e2m1_lut[(pw & 0xF).long()]
                        hi_v = e2m1_lut[(pw >> 4).long()]
                        pw_f = torch.stack((lo_v, hi_v), dim=-1).reshape(probe_n, k_dim // 16, 16)
                        pw_f = (pw_f * ps.unsqueeze(-1) * raw_gs_full.float()).reshape(probe_n, k_dim)
                        x_peak = (
                            pw_f / pw_f.norm(dim=-1, keepdim=True).clamp_min(1e-6) * 1.15
                            + torch.randn((probe_n, k_dim), generator=gen, device=dev)
                            * (1.0 / (k_dim ** 0.5))
                            * 10.0
                        ).to(torch.bfloat16).contiguous()

                        got_peak_top6 = torch.empty((probe_n * 6,), dtype=torch.int64, device=dev)
                        got_peak_vals = torch.empty((probe_n * 6,), dtype=torch.float32, device=dev)
                        got_peak_top2 = torch.empty((4,), dtype=torch.int64, device=dev)
                        got_peak_marg = torch.empty((2,), dtype=torch.float32, device=dev)
                        got_peak_arg = _bfx.dhead_fast_argmax(
                            x_peak, dh_blob, dh_rscales, dh_cscales, dh_toks,
                            tail_ids, tail_count, raw_w_full, raw_s_full, raw_gs_full, 1.0,
                            dh_bits, dh_topk, got_peak_top2, got_peak_marg,
                            got_peak_top6, got_peak_vals,
                        )
                        torch.cuda.synchronize(dev)

                        top1_hits = int((got_peak_arg == probe_orig).sum().item())
                        rescore_err = 0.0
                        if (got_peak_top6[:6] >= 0).all().item():
                            chk_rows = got_peak_top6[:6].to(torch.int32).contiguous()
                            chk_exact = _bfx.draft_vocab_score_rows(
                                x_peak[:1].contiguous(), chk_rows,
                                raw_w_full, raw_s_full, raw_gs_full, 1.0,
                            ).reshape(-1)
                            rescore_err = (got_peak_vals[:6] - chk_exact).abs().max().item()
                        finite_ok = (
                            torch.isfinite(got_peak_vals).all().item()
                            and torch.isfinite(got_peak_marg).all().item()
                            and int((got_peak_arg >= 0).all().item()) == 1
                            and int((got_peak_arg < vocab_n).all().item()) == 1
                        )
                        if finite_ok and top1_hits == probe_n and rescore_err <= 1e-4:
                            class _Fast4D64DraftHeadQuantMethod:
                                def apply(
                                    self,
                                    dh_layer: torch.nn.Module,
                                    x: torch.Tensor,
                                    bias: torch.Tensor | None = None,
                                ) -> torch.Tensor:
                                    x_2d = x.reshape(-1, x.shape[-1])
                                    x_c = x_2d if x_2d.is_contiguous() else x_2d.contiguous()
                                    row_ids = dh_layer.token_ids.to(torch.int32).contiguous()
                                    out = _bfx.draft_vocab_score_rows(
                                        x_c, row_ids, dh_layer.full_raw_w,
                                        dh_layer.full_raw_s, dh_layer.full_global_scale, 1.0,
                                    ).to(x.dtype)
                                    if bias is not None:
                                        out = out + bias
                                    return out.reshape(*x.shape[:-1], int(row_ids.numel()))

                            draft_head.register_buffer("fast_dhead_blob", dh_blob, persistent=False)
                            draft_head.register_buffer("fast_dhead_row_scales", dh_rscales, persistent=False)
                            draft_head.register_buffer("fast_dhead_col_scales", dh_cscales, persistent=False)
                            draft_head.register_buffer("fast_dhead_tok_ids", dh_toks, persistent=False)
                            draft_head.register_buffer("full_raw_w", raw_w_full, persistent=False)
                            draft_head.register_buffer("full_raw_s", raw_s_full, persistent=False)
                            draft_head.register_buffer("full_global_scale", raw_gs_full, persistent=False)
                            draft_head.register_buffer("in_static_vocab", in_static, persistent=False)
                            draft_head.register_buffer("tail_ids", tail_ids, persistent=False)
                            draft_head.register_buffer("tail_count", tail_count, persistent=False)
                            draft_head.register_buffer("tail_seen", tail_seen, persistent=False)
                            draft_head.quant_method = _Fast4D64DraftHeadQuantMethod()
                            draft_head.fast_dhead_mode = dh_bits
                            draft_head.fast_dhead_topk = dh_topk
                            draft_head.fast_dhead_admitted = True
                            draft_head.prompt_tail_admitted = True
                            fast_dhead_admitted = True
                            object.__setattr__(layer, "_draft_vocab_head", draft_head)
                            bpw = 1.000 if dh_bits == 100 else (1.500 if dh_bits == 150 else (1.625 if dh_bits == 158 else 2.000))
                            logger.info(
                                "Fast 2-stage 4D-64 draft head admitted (mode=%d, bpw=%.3f, blob=%.1f MB, "
                                "topk=%d, peaked_top1=%d/%d, rescore_err=%.6f, lat=%.3f ms)",
                                dh_bits,
                                bpw,
                                dh_blob.numel() / (1024.0 * 1024.0),
                                dh_topk,
                                top1_hits,
                                probe_n,
                                rescore_err,
                                best_lat_ms,
                            )
                        else:
                            logger.warning(
                                "Fast 2-stage 4D-64 draft head self-check failed (finite=%s, top1=%d/%d, "
                                "rescore_err=%.6f); falling back",
                                finite_ok,
                                top1_hits,
                                probe_n,
                                rescore_err,
                            )
                except Exception as exc_dh:  # noqa: BLE001
                    logger.warning(
                        "Fast 2-stage 4D-64 draft head skipped (%s); falling back",
                        exc_dh,
                    )

            if want_fast_dhead and not fast_dhead_admitted:
                try:
                    import sys
                    import muse_bfx_ext as _bfx

                    if (
                        hasattr(_bfx, "draft_head_pack")
                        and hasattr(_bfx, "draft_head_topc")
                        and hasattr(_bfx, "draft_head_gemm_full")
                        and hasattr(_bfx, "draft_vocab_tail_argmax")
                        and hasattr(_bfx, "draft_vocab_score_rows")
                    ):
                        dhead_ctas = int(os.environ.get("MUSE_DHEAD_CTAS", "96"))
                        if dhead_ctas not in (48, 96, 192):
                            dhead_ctas = 96
                        dhead_mode = int(os.environ.get("MUSE_DHEAD_MODE", "1"))
                        if dhead_mode not in (0, 1, 2, 3):
                            dhead_mode = 1
                        dhead_rk = int(os.environ.get("MUSE_DHEAD_RESCORE_K", "96"))

                        w_packed = _bfx.draft_head_pack(
                            raw_w_full, raw_s_full, raw_gs_full, ids, dhead_ctas, dhead_mode
                        )
                        if os.environ.get("MUSE_DRAFT_VOCAB_PLACE", "1") != "0":
                            try:
                                spares = [torch.empty_like(w_packed) for _ in range(6)]
                                for sp in spares:
                                    sp.copy_(w_packed)
                                evict = torch.ones((48 << 20) // 4, dtype=torch.float32, device=dev)
                                x_p = (
                                    ((torch.arange(6 * k_dim, device=dev) % 7).float() - 3.0)
                                    .to(torch.bfloat16)
                                    .reshape(6, k_dim)
                                    .contiguous()
                                )
                                cands = [w_packed, *spares]
                                _ = evict.sum()
                                _ = _bfx.draft_head_topc(
                                    x_p, w_packed, ids, len(draft_ids), k_dim, dhead_ctas, dhead_mode, dhead_rk
                                )
                                torch.cuda.synchronize(dev)
                                samples_f: list[list[float]] = [[] for _ in cands]
                                for _ in range(5):
                                    for ci, buf in enumerate(cands):
                                        _ = evict.sum()
                                        se = torch.cuda.Event(enable_timing=True)
                                        ee = torch.cuda.Event(enable_timing=True)
                                        se.record()
                                        _ = _bfx.draft_head_topc(
                                            x_p, buf, ids, len(draft_ids), k_dim, dhead_ctas, dhead_mode, dhead_rk
                                        )
                                        ee.record()
                                        torch.cuda.synchronize(dev)
                                        samples_f[ci].append(se.elapsed_time(ee))
                                times_f = [median(s) for s in samples_f]
                                best_i = min(range(len(cands)), key=times_f.__getitem__)
                                if best_i > 0 and times_f[0] - times_f[best_i] >= 0.005:
                                    w_packed = cands[best_i]
                                    logger.info(
                                        "Fast NF3/VQ draft_head DRAM placement: saved %.3f ms (%.3f -> %.3f ms)",
                                        times_f[0] - times_f[best_i],
                                        times_f[0],
                                        times_f[best_i],
                                    )
                                del spares, cands, evict, x_p
                                torch.cuda.empty_cache()
                            except Exception as exc_p:  # noqa: BLE001
                                logger.warning("Fast draft_head DRAM placement skipped (%s)", exc_p)

                        in_static = torch.zeros((vocab_n,), dtype=torch.uint8, device=dev)
                        in_static.scatter_(0, ids, 1)
                        tail_ids = torch.full((512,), -1, dtype=torch.int32, device=dev)
                        tail_count = torch.zeros((1,), dtype=torch.int32, device=dev)
                        tail_seen = torch.zeros((vocab_n,), dtype=torch.int32, device=dev)

                        gen = torch.Generator(device=dev).manual_seed(20261130)
                        x_chk = (
                            torch.randn((6, k_dim), generator=gen, device=dev) * 0.5
                        ).to(torch.bfloat16).contiguous()
                        approx_logits = _bfx.draft_head_gemm_full(
                            x_chk, w_packed, len(draft_ids), k_dim, dhead_ctas, dhead_mode
                        )
                        n_d = len(draft_ids)
                        chk_idx = torch.tensor(
                            [(j * (n_d - 1)) // 31 for j in range(32)],
                            dtype=torch.long,
                            device=dev,
                        )
                        chk_orig = ids.index_select(0, chk_idx).to(torch.int32).contiguous()
                        got_scores = _bfx.draft_vocab_score_rows(
                            x_chk, chk_orig, raw_w_full, raw_s_full, raw_gs_full, 1.0
                        )
                        approx_scores = approx_logits.index_select(1, chk_idx).float()
                        rel_err = (
                            (got_scores - approx_scores).norm()
                            / got_scores.norm().clamp(min=1e-6)
                        ).item()
                        sent_chk = _bfx.draft_head_topc(
                            x_chk, w_packed, ids, len(draft_ids), k_dim, dhead_ctas, dhead_mode, dhead_rk
                        )
                        tt_chk = torch.empty((36,), dtype=torch.long, device=dev)
                        tv_chk = torch.empty((36,), dtype=torch.float32, device=dev)
                        got_arg = _bfx.draft_vocab_tail_argmax(
                            x_chk, sent_chk, ids, tail_ids, tail_count,
                            raw_w_full, raw_s_full, raw_gs_full, 1.0,
                            None, None, tt_chk, tv_chk, False,
                        )
                        torch.cuda.synchronize(dev)
                        rel_lim = 0.38 if dhead_mode == 2 else 0.35
                        if rel_err <= rel_lim and got_arg.numel() == 6:
                            n_rows_dh = len(draft_ids)
                            k_cols_dh = k_dim

                            class _FastDraftHeadQuantMethod:
                                def apply(
                                    self,
                                    dh_layer: torch.nn.Module,
                                    x: torch.Tensor,
                                    bias: torch.Tensor | None = None,
                                ) -> torch.Tensor:
                                    x_2d = x.reshape(-1, x.shape[-1])
                                    x_c = x_2d if x_2d.is_contiguous() else x_2d.contiguous()
                                    in_draft_argmax = False
                                    if (
                                        bias is None
                                        and 1 <= x_c.shape[0] <= 8
                                        and getattr(dh_layer, "prompt_tail_admitted", False)
                                    ):
                                        frm = sys._getframe(1)
                                        for _ in range(8):
                                            if frm is None:
                                                break
                                            cname = frm.f_code.co_name
                                            if cname == "draft_argmax":
                                                in_draft_argmax = True
                                                break
                                            if cname == "compute_logits":
                                                break
                                            frm = frm.f_back
                                    if in_draft_argmax:
                                        return _bfx.draft_head_topc(
                                            x_c,
                                            dh_layer._dhead_w_packed,
                                            dh_layer.token_ids,
                                            n_rows_dh,
                                            k_cols_dh,
                                            dhead_ctas,
                                            dhead_mode,
                                            dhead_rk,
                                        )
                                    out = _bfx.draft_head_gemm_full(
                                        x_c,
                                        dh_layer._dhead_w_packed,
                                        n_rows_dh,
                                        k_cols_dh,
                                        dhead_ctas,
                                        dhead_mode,
                                    )
                                    if bias is not None:
                                        out = out + bias
                                    return out.reshape(*x.shape[:-1], n_rows_dh)

                            draft_head.register_buffer("_dhead_w_packed", w_packed, persistent=False)
                            draft_head.register_buffer("full_raw_w", raw_w_full, persistent=False)
                            draft_head.register_buffer("full_raw_s", raw_s_full, persistent=False)
                            draft_head.register_buffer("full_global_scale", raw_gs_full, persistent=False)
                            draft_head.register_buffer("in_static_vocab", in_static, persistent=False)
                            draft_head.register_buffer("tail_ids", tail_ids, persistent=False)
                            draft_head.register_buffer("tail_count", tail_count, persistent=False)
                            draft_head.register_buffer("tail_seen", tail_seen, persistent=False)
                            draft_head.quant_method = _FastDraftHeadQuantMethod()
                            draft_head.prompt_tail_admitted = True
                            fast_dhead_admitted = True
                            object.__setattr__(layer, "_draft_vocab_head", draft_head)
                            _dhead_labels = {
                                0: "NF3",
                                1: "VQ2.5",
                                2: "4D-AntiVQ2.0",
                                3: "4D-AntiVQ2.25",
                            }
                            logger.info(
                                "Prepared Hadamard-%s %d-row fused top-C draft_head + exact-NVFP4 top-%d rescore "
                                "(%.2f MB, ctas=%d, wn_rel_err=%.4f)",
                                _dhead_labels.get(dhead_mode, f"mode{dhead_mode}"),
                                len(draft_ids),
                                dhead_rk,
                                w_packed.numel() / 1e6,
                                dhead_ctas,
                                rel_err,
                            )
                        else:
                            logger.warning(
                                "Fast draft_head parity check out of range (wn_rel_err=%.4f); falling back to NVFP4",
                                rel_err,
                            )
                except Exception as exc_fd:  # noqa: BLE001
                    logger.warning("Fast Hadamard-NF3 draft_head skipped (%s); falling back to NVFP4", exc_fd)

            if not fast_dhead_admitted:
                draft_head.register_parameter(
                    "weight",
                    Parameter(
                        layer.weight.index_select(0, ids).contiguous(),
                        requires_grad=False,
                    ),
                )
                draft_head.register_parameter(
                    "weight_scale",
                    Parameter(
                        layer.weight_scale.index_select(0, ids).contiguous(),
                        requires_grad=False,
                    ),
                )
                draft_head.register_parameter(
                    "weight_global_scale",
                    Parameter(layer.weight_global_scale.clone(), requires_grad=False),
                )
                draft_head.quant_method = self
                self.kernel.process_weights_after_loading(draft_head)

                # Quick 6-spare read-only-flush GB10 DRAM placement for draft_head._marlin_decode_weight.
                dec_w = getattr(draft_head, "_marlin_decode_weight", None)
                if (
                    dec_w is not None
                    and os.environ.get("MUSE_DRAFT_VOCAB_PLACE", "1") != "0"
                ):
                    try:
                        spares = [torch.empty_like(dec_w) for _ in range(6)]
                        for sp in spares:
                            sp.copy_(dec_w)
                        evict = torch.ones((48 << 20) // 4, dtype=torch.float32, device=dev)
                        x_p = (
                            ((torch.arange(6 * k_dim, device=dev) % 7).float() - 3.0)
                            .to(torch.bfloat16)
                            .reshape(6, k_dim)
                        )
                        cands = [dec_w, *spares]
                        _ = evict.sum()
                        _ = self.apply(draft_head, x_p)
                        torch.cuda.synchronize(dev)
                        samples: list[list[float]] = [[] for _ in cands]
                        for _ in range(5):
                            for ci, buf in enumerate(cands):
                                draft_head._buffers["_marlin_decode_weight"] = buf
                                _ = evict.sum()
                                se = torch.cuda.Event(enable_timing=True)
                                ee = torch.cuda.Event(enable_timing=True)
                                se.record()
                                _ = self.apply(draft_head, x_p)
                                ee.record()
                                torch.cuda.synchronize(dev)
                                samples[ci].append(se.elapsed_time(ee))
                        times = [median(s) for s in samples]
                        best_i = min(range(len(cands)), key=times.__getitem__)
                        if best_i > 0 and times[0] - times[best_i] >= 0.005:
                            draft_head._buffers["_marlin_decode_weight"] = cands[best_i]
                            logger.info(
                                "Draft vocab head DRAM placement: saved %.3f ms (%.3f -> %.3f ms)",
                                times[0] - times[best_i],
                                times[0],
                                times[best_i],
                            )
                        else:
                            draft_head._buffers["_marlin_decode_weight"] = dec_w
                        del spares, cands, evict, x_p
                        torch.cuda.empty_cache()
                    except Exception as exc:  # noqa: BLE001
                        draft_head._buffers["_marlin_decode_weight"] = dec_w
                        logger.warning("Draft vocab head DRAM placement skipped (%s)", exc)

                if want_tail and raw_w_full is not None and raw_s_full is not None and raw_gs_full is not None:
                    try:
                        import muse_bfx_ext as _bfx

                        if hasattr(_bfx, "draft_vocab_tail_argmax") and hasattr(_bfx, "draft_vocab_score_rows"):
                            in_static = torch.zeros((vocab_n,), dtype=torch.uint8, device=dev)
                            in_static.scatter_(0, ids, 1)
                            tail_ids = torch.full((512,), -1, dtype=torch.int32, device=dev)
                            tail_count = torch.zeros((1,), dtype=torch.int32, device=dev)
                            tail_seen = torch.zeros((vocab_n,), dtype=torch.int32, device=dev)

                            # Scale-parity self-check: compare exact-NVFP4 tail dot product vs Marlin static head.
                            gen = torch.Generator(device=dev).manual_seed(20261130)
                            x_chk = (
                                torch.randn((6, k_dim), generator=gen, device=dev) * 0.5
                            ).to(torch.bfloat16).contiguous()
                            ref_logits = self.apply(draft_head, x_chk)
                            if tuple(ref_logits.shape) != (6, len(draft_ids)):
                                raise RuntimeError(
                                    f"unexpected ref_logits shape {tuple(ref_logits.shape)} != (6, {len(draft_ids)})"
                                )
                            n_d = len(draft_ids)
                            chk_idx = torch.tensor(
                                [0, 1, 127, min(1024, n_d - 1), min(8192, n_d - 1),
                                 min(16384, n_d - 1), min(24576, n_d - 1), n_d - 1],
                                dtype=torch.long,
                                device=dev,
                            )
                            chk_orig = ids.index_select(0, chk_idx).to(torch.int32).contiguous()
                            got_scores = _bfx.draft_vocab_score_rows(
                                x_chk, chk_orig, raw_w_full, raw_s_full, raw_gs_full, 1.0
                            )
                            ref_scores = ref_logits.index_select(1, chk_idx).float()
                            max_err = (got_scores - ref_scores).abs().max().item()
                            tol = 2e-2 * ref_scores.abs().max().item() + 1e-2
                            # Also warmup tail_argmax scratch allocation outside CUDA graph capture.
                            got_arg = _bfx.draft_vocab_tail_argmax(
                                x_chk,
                                ref_logits.contiguous(),
                                ids,
                                tail_ids,
                                tail_count,
                                raw_w_full,
                                raw_s_full,
                                raw_gs_full,
                                1.0,
                            )
                            ref_arg = ids.index_select(0, ref_logits.argmax(dim=-1))
                            torch.cuda.synchronize(dev)
                            if max_err <= tol and torch.equal(got_arg, ref_arg):
                                draft_head.register_buffer("full_raw_w", raw_w_full, persistent=False)
                                draft_head.register_buffer("full_raw_s", raw_s_full, persistent=False)
                                draft_head.register_buffer("full_global_scale", raw_gs_full, persistent=False)
                                draft_head.register_buffer("in_static_vocab", in_static, persistent=False)
                                draft_head.register_buffer("tail_ids", tail_ids, persistent=False)
                                draft_head.register_buffer("tail_count", tail_count, persistent=False)
                                draft_head.register_buffer("tail_seen", tail_seen, persistent=False)
                                draft_head.prompt_tail_admitted = True
                                logger.info(
                                    "Draft vocab dynamic prompt tail admitted (V_static=%d, max_tail=512, parity_err=%.5f)",
                                    len(draft_ids),
                                    max_err,
                                )
                            else:
                                logger.warning(
                                    "Draft vocab dynamic prompt tail parity failed (err=%.5f > %.5f); static-only",
                                    max_err,
                                    tol,
                                )
                    except Exception as exc:  # noqa: BLE001
                        logger.warning("Draft vocab dynamic prompt tail skipped (%s); static-only", exc)

                object.__setattr__(layer, "_draft_vocab_head", draft_head)
                _s6 = getattr(draft_head, "_marlin_decode_scales6", None)
                _is_ilv = False
                if _s6 is not None:
                    try:
                        import muse_marlin6_gemv as _m6_chk
                        _is_ilv = _m6_chk.is_tma4_ilv(_s6)
                    except Exception:  # noqa: BLE001
                        _is_ilv = False
                logger.info(
                    "Prepared contiguous %d-row NVFP4 head for greedy DFlash (tma4_ilv=%s, prompt_tail=%s)",
                    len(draft_ids),
                    _is_ilv,
                    draft_head.prompt_tail_admitted,
                )

        self.kernel.process_weights_after_loading(layer)

    def apply(
        self,
        layer: torch.nn.Module,
        x: torch.Tensor,
        bias: torch.Tensor | None = None,
    ) -> torch.Tensor:
        return self.kernel.apply_weights(layer=layer, x=x, bias=bias)


class ModelOptNvFp4FusedMoE(FusedMoEMethodBase):
    """
    MoE Method for FP4 Quantization.
    Args:
        quant_config: NVFP4 Quant Config
    """

    def __init__(
        self,
        quant_config: ModelOptNvFp4Config,
        moe_config: FusedMoEConfig,
    ) -> None:
        super().__init__(moe_config)
        self.quant_config = quant_config
        # W4A16 mode fires for W4A16_NVFP4 on-disk checkpoints. With
        # activation_key=None every W4A4 backend's _supports_quant_scheme
        # rejects itself (they all require (kNvfp4Static, kNvfp4Dynamic)
        # exactly); only Marlin survives. Marlin's MoE path drops
        # activation scales in convert_to_nvfp4_moe_kernel_format, so no
        # other change is needed.
        self.use_a16 = quant_config.quant_method == "W4A16_NVFP4"
        self.nvfp4_backend, self.experts_cls = select_nvfp4_moe_backend(
            config=self.moe,
            weight_key=kNvfp4Static,
            activation_key=None if self.use_a16 else kNvfp4Dynamic,
        )

        self.use_global_sf = is_global_sf_supported_for_nvfp4_backend(
            self.nvfp4_backend
        )

    def maybe_make_prepare_finalize(
        self,
        routing_tables: tuple[torch.Tensor, torch.Tensor, torch.Tensor] | None = None,
    ) -> mk.FusedMoEPrepareAndFinalizeModular | None:
        raise ValueError(
            f"{self.__class__.__name__} uses the new modular kernel initialization "
            "logic. This function should not be called."
        )

    def uses_weight_scale_2_pattern(self) -> bool:
        """
        FP4 variants use 'weight_scale_2' pattern for per-tensor weight scales.
        """
        return True

    def create_weights(
        self,
        layer: RoutedExperts,
        num_experts: int,
        hidden_size: int,
        intermediate_size_per_partition: int,
        params_dtype: torch.dtype,
        **extra_weight_attrs,
    ):
        assert self.quant_config.is_checkpoint_nvfp4_serialized

        layer.num_experts = num_experts
        layer.params_dtype = params_dtype
        layer.quant_config = self.quant_config
        weight_dtype = torch.uint8
        weight_scale_dtype = torch.float8_e4m3fn
        weight_loader = extra_weight_attrs.get("weight_loader")
        global_num_experts = extra_weight_attrs.get("global_num_experts")
        w13_num_shards = 2 if self.moe.is_act_and_mul else 1
        # GEMM 1
        w13_weight = ModelWeightParameter(
            data=torch.empty(
                num_experts,
                w13_num_shards * intermediate_size_per_partition,
                # 2 fp4 items are packed in the input dimension
                hidden_size // 2,
                dtype=weight_dtype,
            ),
            input_dim=1,
            output_dim=2,
            weight_loader=weight_loader,
        )
        layer.register_parameter("w13_weight", w13_weight)

        # GEMM 2
        w2_weight = ModelWeightParameter(
            data=torch.empty(
                num_experts,
                hidden_size,
                # 2 fp4 items are packed in the input dimension
                intermediate_size_per_partition // 2,
                dtype=weight_dtype,
            ),
            input_dim=1,
            output_dim=2,
            weight_loader=weight_loader,
        )
        layer.register_parameter("w2_weight", w2_weight)

        w13_weight_scale = ModelWeightParameter(
            data=torch.empty(
                num_experts,
                w13_num_shards * intermediate_size_per_partition,
                # 2 fp4 items are packed in the input dimension
                hidden_size // self.quant_config.group_size,
                dtype=weight_scale_dtype,
            ),
            input_dim=1,
            output_dim=2,
            weight_loader=weight_loader,
        )
        layer.register_parameter("w13_weight_scale", w13_weight_scale)

        w2_weight_scale = ModelWeightParameter(
            data=torch.empty(
                num_experts,
                hidden_size,
                # 2 fp4 items are packed in the input dimension
                intermediate_size_per_partition // self.quant_config.group_size,
                dtype=weight_scale_dtype,
            ),
            input_dim=1,
            output_dim=2,
            weight_loader=weight_loader,
        )
        layer.register_parameter("w2_weight_scale", w2_weight_scale)

        extra_weight_attrs.update(
            {"quant_method": FusedMoeWeightScaleSupported.BLOCK.value}
        )

        w13_weight_scale_2 = PerTensorScaleParameter(
            data=torch.empty(num_experts, w13_num_shards, dtype=torch.float32),
            weight_loader=weight_loader,
        )
        layer.register_parameter("w13_weight_scale_2", w13_weight_scale_2)

        w2_weight_scale_2 = PerTensorScaleParameter(
            data=torch.empty(num_experts, dtype=torch.float32),
            weight_loader=weight_loader,
        )
        layer.register_parameter("w2_weight_scale_2", w2_weight_scale_2)

        extra_weight_attrs.update(
            {"quant_method": FusedMoeWeightScaleSupported.TENSOR.value}
        )

        global_sf_num_experts = (
            global_num_experts if self.use_global_sf else num_experts
        )
        w13_input_scale = PerTensorScaleParameter(
            data=torch.empty(
                global_sf_num_experts,
                w13_num_shards,
                dtype=torch.float32,
            ),
            weight_loader=weight_loader,
        )
        layer.register_parameter("w13_input_scale", w13_input_scale)

        w2_input_scale = PerTensorScaleParameter(
            data=torch.empty(global_sf_num_experts, dtype=torch.float32),
            weight_loader=weight_loader,
        )
        layer.register_parameter("w2_input_scale", w2_input_scale)

    def process_weights_after_loading(self, layer: RoutedExperts) -> None:
        """
        Convert NVFP4 MoE weights into kernel format and setup the kernel.
        """

        # Use a single gscale for w13.
        if self.moe.is_act_and_mul and not torch.allclose(
            layer.w13_weight_scale_2[:, 0], layer.w13_weight_scale_2[:, 1]
        ):
            logger.warning_once(
                "w1_weight_scale_2 must match w3_weight_scale_2. "
                "Accuracy may be affected."
            )
        w13_weight_scale_2 = layer.w13_weight_scale_2[:, 0].contiguous()

        (
            w13,
            w13_scale,
            w13_scale_2,
            a13_scale,
            w2,
            w2_scale,
            w2_scale_2,
            a2_scale,
        ) = convert_to_nvfp4_moe_kernel_format(
            nvfp4_backend=self.nvfp4_backend,
            layer=layer,
            w13=layer.w13_weight,
            w13_scale=layer.w13_weight_scale,
            w13_scale_2=w13_weight_scale_2,
            a13_scale=layer.w13_input_scale,
            w2=layer.w2_weight,
            w2_scale=layer.w2_weight_scale,
            w2_scale_2=layer.w2_weight_scale_2,
            a2_scale=layer.w2_input_scale,
            is_act_and_mul=self.moe.is_act_and_mul,
        )

        replace_parameter(layer, "w13_weight", w13)
        replace_parameter(layer, "w13_weight_scale", w13_scale)
        replace_parameter(layer, "w13_weight_scale_2", w13_scale_2)
        replace_parameter(layer, "w13_input_scale", a13_scale)
        replace_parameter(layer, "w2_weight", w2)
        replace_parameter(layer, "w2_weight_scale", w2_scale)
        replace_parameter(layer, "w2_weight_scale_2", w2_scale_2)
        replace_parameter(layer, "w2_input_scale", a2_scale)

        # Setup modular kernel.
        self.moe_quant_config = self.get_fused_moe_quant_config(layer)
        assert self.experts_cls is not None
        self.moe_kernel = make_nvfp4_moe_kernel(
            moe_quant_config=self.moe_quant_config,
            moe_config=self.moe,
            experts_cls=self.experts_cls,
            backend=self.nvfp4_backend,
            routing_tables=layer._expert_routing_tables(),
            layer=layer,
        )
        self.moe_kernel.fused_experts.process_weights_after_loading(layer)

    def get_fused_moe_quant_config(self, layer: RoutedExperts) -> FusedMoEQuantConfig:
        return make_nvfp4_moe_quant_config(
            backend=self.nvfp4_backend,
            w13_scale=layer.w13_weight_scale,
            w2_scale=layer.w2_weight_scale,
            w13_scale_2=layer.w13_weight_scale_2,
            w2_scale_2=layer.w2_weight_scale_2,
            a13_scale=layer.w13_input_scale,
            a2_scale=layer.w2_input_scale,
            swiglu_limit=getattr(layer, "swiglu_limit", None),
            layer=layer,
        )

    @property
    def supports_eplb(self) -> bool:
        return True

    def apply_monolithic(
        self,
        layer: RoutedExperts,
        x: torch.Tensor,
        router_logits: torch.Tensor,
        input_ids: torch.Tensor | None = None,
    ) -> torch.Tensor:
        assert self.is_monolithic
        assert self.moe_kernel is not None
        return self.moe_kernel.apply_monolithic(
            x,
            layer.w13_weight,
            layer.w2_weight,
            router_logits,
            activation=layer.activation,
            global_num_experts=layer.global_num_experts,
            expert_map=layer.expert_map,
            apply_router_weight_on_input=layer.apply_router_weight_on_input,
            num_expert_group=layer.num_expert_group,
            topk_group=layer.topk_group,
            e_score_correction_bias=layer.e_score_correction_bias,
            routed_scaling_factor=layer.routed_scaling_factor,
        )

    def apply(
        self,
        layer: RoutedExperts,
        x: torch.Tensor,
        topk_weights: torch.Tensor,
        topk_ids: torch.Tensor,
        shared_experts: SharedExperts | None,
        shared_experts_input: torch.Tensor | None,
    ) -> torch.Tensor:
        assert not self.is_monolithic
        assert self.moe_kernel is not None
        return self.moe_kernel.apply(
            x,
            layer.w13_weight,
            layer.w2_weight,
            topk_weights,
            topk_ids,
            activation=layer.activation,
            global_num_experts=layer.global_num_experts,
            expert_map=layer.expert_map,
            apply_router_weight_on_input=layer.apply_router_weight_on_input,
            shared_experts=shared_experts,
            shared_experts_input=shared_experts_input,
        )


